"""
20_input_register.py -- the nine-crop input register (plan P2) -> docs/input_register.csv and .md
One row per crop: production item and panel, crop map and irrigation, calendar and fallbacks, heat and water
parameters with sources, food-balance / composition mapping, proxies, expected bias, sensitivity range and
reviewer sign-off. Data-derived fields are computed here; literature fields come from config.CROPS.
"""
import os

import numpy as np
import pandas as pd

from config import CROP_ORDER, CROPS, PROC, ROOT_DIR, WORK, season_kc

DOCS = os.path.join(ROOT_DIR, "docs")


def main():
    panels = pd.read_csv(os.path.join(PROC, "panels.csv"))
    comp = pd.read_csv(os.path.join(PROC, "composition_used.csv")).set_index("fbs_item")
    rows = []
    for crop in [c for c in CROP_ORDER if c in CROPS]:
        info = CROPS[crop]
        g = np.load(os.path.join(WORK, f"grids_{crop}.npz"))
        A, I, src = g["area_A"], g["area_I"], g["cal_src"]
        tot = A.sum()
        share = lambda code: 100 * A[(A > 0) & np.isin(src, code)].sum() / tot
        p = panels[panels.crop == crop].sort_values("rank")
        items = info.get("fbs_items", []) + info.get("sua_items", [])
        usda = "; ".join(f"{it} -> {comp.loc[it, 'description'] if it in comp.index else '?'} (fdc {int(comp.loc[it, 'fdc_id']) if it in comp.index else '?'})" for it in items)
        tlim = info.get("tlim")
        rows.append({
            "crop": crop, "group": info["group"], "label": info["label"],
            "faostat_production_item": info["faostat_item"],
            "panel_countries": "; ".join(f"{c} ({r})" for c, r in zip(p.country, p["rank"])),
            "n_countries": len(p), "panel_reference_years": p.years.iloc[0],
            "panel_share_of_world_production_pct": round(p.share_pct.sum(), 1),
            "small_producers_flagged": "; ".join(p[p.small_producer].country) or "none",
            "crop_map": f"SPAM 2010 v2.0 {info['spam']} (harvested area A, irrigated I, rainfed R; 5' summed to 10')",
            "global_area_Mha": round(tot / 1e6, 1), "irrigated_share_pct": round(100 * I.sum() / tot, 1),
            "calendar": ("cool-season rule (03_build_grids.py): " + ("own observed Sacks " + "/".join(info.get("sacks_observed_first", [])) + " first; " if info.get("sacks_observed_first") else "")
                         + "Koppen-D cells -> Sacks spring Wheat; other cells -> wheat rule") if info.get("calendar_rule") == "cool_season"
                        else "Sacks " + " then ".join(info["sacks"]) + " (observed, then filled)",
            "calendar_observed_pct_area": round(share([1]), 1), "calendar_filled_pct_area": round(share([2]), 1),
            "calendar_wheat_proxy_pct_area": round(share([3, 4]), 1),
            "seasons_represented": info.get("seasons_note", "one main season per cell (Sacks); multiple seasons not represented"),
            "T_crit_C": info["tcrit"], "T_lim_C": tlim if tlim else "",
            "heat_slope_per_C": round(info["heat_slope"], 4) if info["heat_slope"] else "",
            "heat_source": info["heat_source"], "heat_metric_and_outcome": info.get("heat_metric", ""),
            "K_y": info["ky"], "K_y_source": info["ky_source"],
            "K_c_ini_mid_end": "/".join(str(x) for x in info["kc"]) if info["kc"] else "",
            "stage_days_ini_dev_mid_late": "/".join(str(x) for x in info["stages"]) if info["stages"] else "",
            "season_average_K_c": round(season_kc(crop), 3) if info["kc"] else "",
            "kc_source": info.get("kc_source", "FAO-56 Tables 11-12"),
            "food_balance_items": "; ".join(info.get("fbs_items", [])) or "none (see SUA)",
            "sua_items": "; ".join(info.get("sua_items", [])) or "",
            "oil_or_processed_treatment": info.get("oil_note", ""),
            "usda_composition_mapping": usda, "nutrients_counted": "kcal, protein, fat (FAOSTAT); zinc, iron (USDA x food quantity)",
            "proxies_and_approximations": info.get("proxy_notes", ""),
            "expected_bias": info.get("expected_bias", ""),
            "sensitivity_range_tested": info.get("sens_range_note", ""),
            "missing_inputs": info.get("missing_inputs", "none"),
            "reviewer_signoff": "pending (team reviewer to check parameter vs source, one calculation, interpretation)",
        })
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(DOCS, "input_register.csv"), index=False)
    with open(os.path.join(DOCS, "input_register.md"), "w", encoding="utf-8") as f:
        f.write("# Nine-crop input register\n\nGenerated by `code/20_input_register.py` from `config.py`, the panels and the grids. "
                "Literature verification: `docs/literature_verification.md` (original four crops, mid-evaluation), "
                "`docs/literature_verification_new_crops.md` (five new crops). Decisions: `docs/DECISION_REGISTER_END_EVAL.md`.\n\n")
        for _, r in df.iterrows():
            f.write(f"## {r.label} ({r.group})\n\n")
            for k, v in r.items():
                if k not in ("crop", "label", "group"):
                    f.write(f"- **{k.replace('_', ' ')}**: {v}\n")
            f.write("\n")
    print(df[["crop", "n_countries", "panel_share_of_world_production_pct", "irrigated_share_pct", "calendar_observed_pct_area",
              "calendar_filled_pct_area", "calendar_wheat_proxy_pct_area", "T_crit_C", "heat_slope_per_C", "K_y"]].to_string(index=False))


if __name__ == "__main__":
    main()
