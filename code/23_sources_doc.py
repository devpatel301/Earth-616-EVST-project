"""
23_sources_doc.py -- writes docs/evidence/india_hyderabad_sources.md from data/external/india_hyderabad_indicators.csv:
one section per source (citation, URL, saved file, granularity, row count, the tables/pages used) plus the
limits that matter for interpreting the Hyderabad analysis.
"""
import os

import pandas as pd

from config import ROOT_DIR

CSV = os.path.join(ROOT_DIR, "data", "external", "india_hyderabad_indicators.csv")
OUT = os.path.join(ROOT_DIR, "docs", "evidence", "india_hyderabad_sources.md")

GRANULARITY = {
    "HCES2324_A10S": "State x rural/urban household consumption (quantity and value per person per 30 days). Not city-level: Telangana urban is the nearest description of Hyderabad.",
    "NSS592": "State x rural/urban HCES 2023-24 report tables (expenditure shares).",
    "NSS594": "State x rural/urban nutrient intake (energy, protein, fat) and food-group shares, 2022-23 and 2023-24.",
    "NFHS5_TG_FS": "NFHS-5 Telangana state fact sheet (urban, rural, total; NFHS-4 for trend).",
    "NFHS5_IN_FS": "NFHS-5 India key indicators (comparison).",
    "NFHS5_TG_REP": "NFHS-5 Telangana state report: food-frequency tables for women and men 15-49, child feeding, anaemia.",
    "NFHS5_HYD_DFS": "NFHS-5 Hyderabad DISTRICT fact sheet (fully urban) via the official data.gov.in API. Values printed in parentheses or as * in the source are small-sample and are not used.",
    "CNNS_TG_FS": "CNNS 2016-18 Telangana fact sheet: serum ferritin, zinc, anaemia, vitamins (children 1-4, 5-9, adolescents 10-19).",
    "CNNS_NAT": "CNNS 2016-18 national report tables.",
    "IFCT2017": "ICMR-NIN Indian Food Composition Tables 2017, Table 5 (iron, zinc; mg per 100 g edible portion, raw foods).",
    "TG_DES_AAG2024": "Telangana Directorate of Economics and Statistics, At a Glance 2024: crop area and production 2023-24 (provisional), rainfall.",
    "TG_SEO2025": "Telangana Socio-Economic Outlook 2025: yields, rainfall, net area sown.",
    "NNMB_URBAN": "ICMR-NIN NNMB urban brief report: pooled urban India (16 states); Telangana is NOT included, so it is not used for Hyderabad.",
}


def main():
    d = pd.read_csv(CSV)
    lines = ["# India / Telangana / Hyderabad: official data used", "",
             "Generated by `code/23_sources_doc.py` from `data/external/india_hyderabad_indicators.csv` "
             f"({len(d)} rows, one number per row with its table or page). Original files are in `data/raw/india/`. "
             "Nothing here is estimated: derived quantities (Shannon diversity, nutrient from quantity x composition, "
             "yield change) are computed in `code/hyderabad_diet.py` and `code/21_india_hyderabad.py` from these rows.", ""]
    for s, g in d.groupby("source_short", sort=False):
        first = g.iloc[0]
        lines += [f"## {s}", "", f"- **Citation:** {first.source_full_citation}", f"- **URL:** {first.url}", f"- **Saved file:** `{first.file_saved}`",
                  f"- **Granularity and use:** {GRANULARITY.get(s, '')}", f"- **Rows:** {len(g)}; read level: {', '.join(sorted(g.read_level.dropna().unique()))}",
                  f"- **Tables/pages (examples):** {'; '.join(g.table_or_page.dropna().astype(str).drop_duplicates().head(4))}", ""]
    lines += ["## Limits", "",
              "- HCES and NSS 594 describe households' acquired quantities and intake by state and rural/urban sector, not Hyderabad city.",
              "- NFHS-5 district values have smaller samples; values in parentheses or `*` in the source are excluded.",
              "- IFCT values are for raw foods (cooking and processing losses not counted); the iron and zinc computed from HCES quantities cover only the listed grains and pulses and are lower bounds.",
              "- Tur (pigeon pea) and moong are major in Hyderabad's diet but are not among the nine crops of the index.",
              "- Telangana's state crop statistics (2023-24, provisional) show paddy area about three times the 2010 SPAM map used by the index.",
              "- Not found: Hyderabad-city-specific intake (NNMB urban excludes Telangana); micronutrient intake surveys for Hyderabad."]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(lines), "lines")


if __name__ == "__main__":
    main()
